"""摆动腿轨迹：smoothstep 插值 + 半余弦抬脚（两端速度为零，软起落）。"""
import numpy as np


def bezier_swing(s, p0, p3, lift=0.04):
    """摆动相足端轨迹：从离地点 p0 到目标落足点 p3，抬脚 lift。

    软起落设计（重要）：罚函数接触没有碰撞动力学，若足端以 ~0.5 m/s
    撞向表面（三次 Bézier 的末端速度 3(p3−p2)/T_sw），法向阻尼 d_n·v_n
    会在触地瞬间产生 ~800 N 的脉冲——在平地把躯干弹起（实测体高漂到
    0.26 m），在天花板（θ=180°）把躯干推离表面导致脱落。MPC 模型不含
    该脉冲 → 每步注入能量。因此：
    - 位置用 smoothstep S(s)=10s³−15s⁴+6s⁵ 插值 p0→p3（S'(0)=S'(1)=0）
    - 抬脚用 (1−cos2πs)/2 半波（两端导数也为 0）
    离地与触地速度均为零，法向阻尼项在触地瞬间无脉冲。

    s: (...,) 归一化摆动进度 [0,1]；p0/p3: (..., 2) 世界坐标；
    返回 (..., 2)。
    """
    s = np.clip(np.asarray(s, dtype=float), 0.0, 1.0)[..., None]
    S = s * s * s * (10.0 - 15.0 * s + 6.0 * s * s)      # smoothstep
    bump = 0.5 * (1.0 - np.cos(2.0 * np.pi * s))          # 半余弦抬脚
    return p0 + (p3 - p0) * S + np.array([0.0, lift]) * bump
